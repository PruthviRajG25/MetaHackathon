import { NextResponse } from "next/server";
import { getSession } from "@/lib/security/auth";
import { connectDB } from "@/lib/db";
import { ShoppingList } from "@/models/ShoppingList";
import { InventoryItem } from "@/models/InventoryItem";
import { PurchaseHistory } from "@/models/PurchaseHistory";

export async function GET(req: Request) {
  try {
    const session = await getSession();
    if (!session) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    let list: any = null;
    try {
      await connectDB();
      const query: any = session.householdId
        ? { householdId: session.householdId, status: "active" }
        : { userId: session.userId, status: "active" };

      list = await ShoppingList.findOne(query);

      if (!list) {
        list = await ShoppingList.create({
          userId: session.userId,
          householdId: session.householdId,
          name: "Weekly Household Shopping",
          status: "active",
          budget: 150,
          items: [],
        });
      }
    } catch (dbErr) {
      console.warn("Shopping list DB fallback:", dbErr);
      list = {
        _id: "default_list",
        name: "Weekly Household Shopping",
        status: "active",
        budget: 150,
        items: [
          {
            _id: "shop_item_1",
            name: "Whole Milk",
            category: "Dairy",
            quantity: 2,
            unit: "litres",
            estimatedPrice: 4.89,
            isPurchased: false,
            priority: "high",
          }
        ],
      };
    }

    // Calculate estimated total cost
    const estimatedTotal = (list.items || []).reduce(
      (sum: number, item: any) => sum + (item.isPurchased ? 0 : (item.estimatedPrice || 0) * (item.quantity || 1)),
      0
    );

    return NextResponse.json({
      list,
      estimatedTotal: Math.round(estimatedTotal * 100) / 100,
    });
  } catch (error: any) {
    console.error("Shopping list fetch error:", error);
    return NextResponse.json({
      list: { name: "Weekly Household Shopping", budget: 150, items: [] },
      estimatedTotal: 0,
    });
  }
}

export async function POST(req: Request) {
  try {
    const session = await getSession();
    if (!session) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    const body = await req.json();
    const { action, item, items, budget } = body;
    await connectDB();

    const query: any = session.householdId
      ? { householdId: session.householdId, status: "active" }
      : { userId: session.userId, status: "active" };

    let list: any = await ShoppingList.findOne(query);
    if (!list) {
      list = await ShoppingList.create({
        userId: session.userId,
        householdId: session.householdId,
        name: "Weekly Household Shopping",
        status: "active",
        budget: budget || 150,
        items: [],
      });
    }

    if (action === "update_budget" && typeof budget === "number") {
      list.budget = budget;
      await list.save();
      return NextResponse.json({ success: true, list });
    }

    if (action === "add_item" && item) {
      list.items.push({
        name: item.name,
        brand: item.brand || null,
        category: item.category || "Other",
        quantity: item.quantity || 1,
        unit: item.unit || "items",
        estimatedPrice: item.estimatedPrice || 0,
        isPurchased: false,
        priority: item.priority || "medium",
        isAutoGenerated: false,
        notes: item.notes,
      } as any);
      await list.save();
      return NextResponse.json({ success: true, list });
    }

    if (action === "mark_purchased" && item?._id) {
      const targetItem = list.items.id(item._id);
      if (targetItem) {
        targetItem.isPurchased = !targetItem.isPurchased;
        targetItem.purchasedQuantity = targetItem.quantity;

        // If newly marked purchased, auto-sync with Inventory
        if (targetItem.isPurchased) {
          if (targetItem.itemId) {
            const inv = await InventoryItem.findById(targetItem.itemId);
            if (inv) {
              inv.quantity += targetItem.quantity;
              inv.lastPurchasedDate = new Date();
              await inv.save();
            }
          } else {
            // Find by matching name or create new
            const inv = await InventoryItem.findOne({
              name: { $regex: new RegExp(`^${targetItem.name}$`, "i") },
              ...(session.householdId ? { householdId: session.householdId } : { userId: session.userId }),
            });
            if (inv) {
              inv.quantity += targetItem.quantity;
              inv.lastPurchasedDate = new Date();
              await inv.save();
            } else {
              await InventoryItem.create({
                name: targetItem.name,
                brand: targetItem.brand,
                category: targetItem.category,
                quantity: targetItem.quantity,
                unit: targetItem.unit,
                userId: session.userId,
                householdId: session.householdId,
                purchasePrice: targetItem.estimatedPrice,
                source: "manual",
                lastPurchasedDate: new Date(),
              });
            }
          }

          // Record in purchase history
          if (targetItem.estimatedPrice && targetItem.estimatedPrice > 0) {
            await PurchaseHistory.create({
              userId: session.userId,
              householdId: session.householdId,
              productName: targetItem.name,
              brand: targetItem.brand,
              category: targetItem.category,
              quantity: targetItem.quantity,
              unit: targetItem.unit,
              price: targetItem.estimatedPrice * targetItem.quantity,
              purchaseDate: new Date(),
            });
          }
        }

        await list.save();
      }
      return NextResponse.json({ success: true, list });
    }

    if (action === "remove_item" && item?._id) {
      list.items = list.items.filter((i: any) => i._id.toString() !== item._id) as any;
      await list.save();
      return NextResponse.json({ success: true, list });
    }

    if (action === "clear_purchased") {
      list.items = list.items.filter((i: any) => !i.isPurchased) as any;
      await list.save();
      return NextResponse.json({ success: true, list });
    }

    if (action === "set_items" && Array.isArray(items)) {
      list.items = items as any;
      await list.save();
      return NextResponse.json({ success: true, list });
    }

    return NextResponse.json({ success: true, list });
  } catch (error: any) {
    console.error("Shopping list update error:", error);
    return NextResponse.json({ error: "Failed to update shopping list" }, { status: 500 });
  }
}
