import mongoose, { Schema, Document, Model } from "mongoose";
import { GROCERY_CATEGORIES, UNITS, GroceryCategory, UnitType } from "@/types";

export interface IShoppingListItemDocument {
  _id?: mongoose.Types.ObjectId;
  itemId?: mongoose.Types.ObjectId;
  name: string;
  brand?: string | null;
  category: GroceryCategory;
  quantity: number;
  unit: UnitType;
  estimatedPrice?: number;
  isPurchased: boolean;
  purchasedQuantity?: number;
  priority: "high" | "medium" | "low";
  isAutoGenerated: boolean;
  notes?: string;
}

export interface IShoppingListDocument extends Document {
  userId: mongoose.Types.ObjectId;
  householdId?: mongoose.Types.ObjectId;
  name: string;
  status: "active" | "archived";
  budget?: number;
  items: IShoppingListItemDocument[];
  createdAt: Date;
  updatedAt: Date;
}

const ShoppingListItemSchema = new Schema<IShoppingListItemDocument>(
  {
    itemId: { type: Schema.Types.ObjectId, ref: "InventoryItem" },
    name: { type: String, required: true, trim: true },
    brand: { type: String, trim: true, default: null },
    category: {
      type: String,
      enum: GROCERY_CATEGORIES,
      default: "Other",
    },
    quantity: { type: Number, required: true, default: 1, min: 0.1 },
    unit: { type: String, enum: UNITS, default: "items" },
    estimatedPrice: { type: Number, min: 0, default: 0 },
    isPurchased: { type: Boolean, default: false },
    purchasedQuantity: { type: Number, min: 0 },
    priority: { type: String, enum: ["high", "medium", "low"], default: "medium" },
    isAutoGenerated: { type: Boolean, default: false },
    notes: { type: String, trim: true },
  },
  { _id: true }
);

const ShoppingListSchema = new Schema<IShoppingListDocument>(
  {
    userId: { type: Schema.Types.ObjectId, ref: "User", required: true, index: true },
    householdId: { type: Schema.Types.ObjectId, ref: "Household", index: true },
    name: { type: String, required: true, default: "Weekly Restock", trim: true },
    status: { type: String, enum: ["active", "archived"], default: "active", index: true },
    budget: { type: Number, min: 0, default: 0 },
    items: [ShoppingListItemSchema],
  },
  { timestamps: true }
);

export const ShoppingList: Model<IShoppingListDocument> =
  mongoose.models.ShoppingList ||
  mongoose.model<IShoppingListDocument>("ShoppingList", ShoppingListSchema);
