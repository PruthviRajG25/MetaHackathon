import { IInventoryItem, IShoppingListItem } from "@/types";
import { evaluateStockStatus } from "./stock-calculator";

export interface RestockRecommendation {
  item: IInventoryItem;
  reason: "critical_empty" | "below_threshold" | "near_depletion" | "expired";
  suggestedQuantity: number;
  priority: "high" | "medium" | "low";
  estimatedDaysLeft: number | null;
}

export function generateRestockRecommendations(
  items: IInventoryItem[],
  householdSize: number = 2
): RestockRecommendation[] {
  const recommendations: RestockRecommendation[] = [];

  for (const item of items) {
    const analysis = evaluateStockStatus(
      {
        quantity: item.quantity,
        minThreshold: item.minThreshold,
        category: item.category,
        expiryDate: item.expiryDate,
        lastPurchasedDate: item.lastPurchasedDate,
      },
      householdSize
    );

    if (analysis.status === "expired") {
      recommendations.push({
        item,
        reason: "expired",
        suggestedQuantity: Math.max(1, item.minThreshold),
        priority: "high",
        estimatedDaysLeft: 0,
      });
    } else if (analysis.status === "critical") {
      recommendations.push({
        item,
        reason: "critical_empty",
        suggestedQuantity: analysis.suggestedRestockQuantity,
        priority: "high",
        estimatedDaysLeft: 0,
      });
    } else if (analysis.status === "low") {
      recommendations.push({
        item,
        reason: "below_threshold",
        suggestedQuantity: analysis.suggestedRestockQuantity,
        priority: "high",
        estimatedDaysLeft: analysis.depletionDaysEstimate,
      });
    } else if (analysis.depletionDaysEstimate !== null && analysis.depletionDaysEstimate <= 3) {
      recommendations.push({
        item,
        reason: "near_depletion",
        suggestedQuantity: analysis.suggestedRestockQuantity,
        priority: "medium",
        estimatedDaysLeft: analysis.depletionDaysEstimate,
      });
    }
  }

  // Sort by priority high to low, then by lowest days left
  return recommendations.sort((a, b) => {
    const pOrder = { high: 0, medium: 1, low: 2 };
    if (pOrder[a.priority] !== pOrder[b.priority]) {
      return pOrder[a.priority] - pOrder[b.priority];
    }
    const daysA = a.estimatedDaysLeft ?? 999;
    const daysB = b.estimatedDaysLeft ?? 999;
    return daysA - daysB;
  });
}

export function convertRecommendationsToShoppingListItems(
  recommendations: RestockRecommendation[]
): IShoppingListItem[] {
  return recommendations.map((rec) => ({
    itemId: rec.item._id?.toString(),
    name: rec.item.name,
    brand: rec.item.brand || null,
    category: rec.item.category,
    quantity: rec.suggestedQuantity,
    unit: rec.item.unit,
    estimatedPrice: rec.item.purchasePrice ? rec.item.purchasePrice * rec.suggestedQuantity : 0,
    isPurchased: false,
    priority: rec.priority,
    isAutoGenerated: true,
    notes: `Auto-restock: ${rec.reason.replace("_", " ")} (${rec.item.quantity} ${rec.item.unit} in stock)`,
  }));
}
